  /**
   * Translate a UI key into the selected language
   * @param {string} key
   * @param {string} lang
   * @returns {string}
   */
  t(key, lang = 'en') {
    const dict = this.translations[lang] || this.translations['en'];
    if (dict && dict[key]) {
      return dict[key];
    }
    // Fallback to English
    if (this.translations['en'] && this.translations['en'][key]) {
      return this.translations['en'][key];
    }
    return key;
  },

  /**
   * Check if language direction is Right-to-Left (RTL)
   * @param {string} lang
   * @returns {boolean}
   */
  isRTL(lang) {
    return ['ur', 'ks', 'sd'].includes(lang);
  },

  /**
   * Get metadata for language code
   * @param {string} langCode
   * @returns {Object}
   */
  getLangMeta(langCode) {
    return this.languages.find(l => l.code === langCode) || this.languages[0];
  }
